test("the cross-build compiles the executable and store for five independent targets", async (t) => {
  const root = await fixtureRepo(t);
  const calls = [];
  const removed = [];
  const outputDirectory = path.join(tmpdir(), "injected-cli-build-success");
  const result = await verifyCLI(root, {
    createBuildDirectory: async () => outputDirectory,
    removeBuildDirectory: async (...args) => removed.push(args),
    runBuild: async (command, args, options) => calls.push({ command, args, options }),
  });

  const expectedTargets = [
    ["linux", "amd64"],
    ["linux", "arm64"],
    ["darwin", "amd64"],
    ["darwin", "arm64"],
    ["windows", "amd64"],
  ];
  assert.deepEqual(
    calls.map(({ options }) => [options.env.GOOS, options.env.GOARCH]),
    expectedTargets.flatMap((target) => [target, target]),
  );
  assert.equal(new Set(calls.map(({ args }) => args[2])).size, expectedTargets.length * 2);
  assert.deepEqual(
    calls.filter(({ args }) => args[3] === "./cmd/vsk-labs").map(({ args }) => path.basename(args[2])),
    [
      "vsk-labs-linux-amd64",
      "vsk-labs-linux-arm64",
      "vsk-labs-darwin-amd64",
      "vsk-labs-darwin-arm64",
      "vsk-labs-windows-amd64.exe",
    ],
  );
  assert.deepEqual(
    calls.filter(({ args }) => args[3] === "./internal/store").map(({ args }) => path.basename(args[2])),
    [
      "store-linux-amd64.a",
      "store-linux-arm64.a",
      "store-darwin-amd64.a",
      "store-darwin-arm64.a",
      "store-windows-amd64.a",
    ],
  );
  assert.deepEqual(result, {
    status: "pass",
    codes: [],
    targetsBuilt: expectedTargets.map(([goos, goarch]) => `${goos}/${goarch}`),
  });
  assert.deepEqual(removed, [[outputDirectory, { recursive: true, force: true }]]);
});

test("the cross-build cleans its isolated output after a mid-matrix failure", async (t) => {
  const root = await fixtureRepo(t);
  const outputs = [];
  const removed = [];
  const outputDirectory = path.join(tmpdir(), "injected-cli-build-failure");
  const result = await verifyCLI(root, {
    createBuildDirectory: async () => outputDirectory,
    removeBuildDirectory: async (...args) => removed.push(args),
    runBuild: async (_command, args) => {
      outputs.push(args[2]);
      if (outputs.length === 3) throw new Error("injected cross-build failure");
    },
  });

  assert.equal(outputs.length, 3);
  assert.equal(new Set(outputs).size, 3);
  assert.deepEqual(result, { status: "fail", codes: ["CLI_CROSS_BUILD"], targetsBuilt: [] });
  assert.deepEqual(removed, [[outputDirectory, { recursive: true, force: true }]]);
});
