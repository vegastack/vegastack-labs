const MATCHING_RUN = [
  "func Run() generated.Command {",
  "  for _, command := range generated.Commands {",
  "    if len(command.Path) > 0 { return command }",
  "  }",
  "  return generated.Command{}",
  "}",
].join("\n");

const BASE_FILES = {
  "go.mod": "module example.test\n\ngo 1.27.0\n",
  "cmd/vsk-labs/main.go": [
    "package main",
    'import "example.test/internal/cli"',
    "func main() { cli.Run() }",
    "",
  ].join("\n"),
  "internal/cli/run.go": [
    "package cli",
    'import "example.test/internal/generated"',
    MATCHING_RUN,
    "",
  ].join("\n"),
  "internal/generated/contracts_gen.go": [
    "// Code generated by fixture; DO NOT EDIT.",
    "package generated",
    'const RegistrySchemaVersion = "1.0.0"',
    "type Command struct { Path []string }",
    "var Commands = []Command{}",
    "",
  ].join("\n"),
};

async function fixtureRepo(t, files = {}) {
  const root = await mkdtemp(path.join(tmpdir(), "vegastack-cli-fixture-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const contents = { ...BASE_FILES, ...files };
  await Promise.all(
    Object.entries(contents).map(async ([relative, content]) => {
      const destination = path.join(root, relative);
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, content, "utf8");
    }),
  );
  return root;
}

test("the CLI verifier accepts one generated-registry consumer", async (t) => {
  const root = await fixtureRepo(t);
  const result = await verifyCLI(root, { crossBuild: false });
  assert.deepEqual(result, { status: "pass", codes: [], targetsBuilt: [] });
});

